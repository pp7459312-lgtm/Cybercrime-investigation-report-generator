-- 1. Users Table (Role-based access: 'user' or 'admin')
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    username TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user',
    created_at TEXT NOT NULL
);

-- Index on username and email for high-speed authentication lookup
CREATE INDEX IF NOT EXISTS idx_users_username ON users(username);
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);


-- 2. Incidents Table (Full Complaint Lifecycle & Digital Forensic Records)
CREATE TABLE IF NOT EXISTS incidents (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    case_id TEXT UNIQUE NOT NULL,
    user_id INTEGER,
    title TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Other',
    incident_date TEXT,
    description TEXT NOT NULL,
    supporting_info TEXT,
    status TEXT NOT NULL DEFAULT 'Pending',
    investigation_notes TEXT,
    resolution TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- Indexes for rapid case lookup and filtering
CREATE INDEX IF NOT EXISTS idx_incidents_case_id ON incidents(case_id);
CREATE INDEX IF NOT EXISTS idx_incidents_user_id ON incidents(user_id);
CREATE INDEX IF NOT EXISTS idx_incidents_status ON incidents(status);
CREATE INDEX IF NOT EXISTS idx_incidents_category ON incidents(category);


